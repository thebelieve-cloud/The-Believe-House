// 0.5 -> "500 เมตร", 2.1 -> "2.1 กิโลเมตร"
export function formatDistance(km: number): string {
    return km < 1 ? `${Math.round(km * 1000)} เมตร` : `${km.toFixed(1)} กิโลเมตร`;
}
